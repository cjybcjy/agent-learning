def infer_sector(name: str) -> str:
    """Infer sector from stock name."""
    for keywords, sector in KEYWORD_MAP:
        for kw in keywords:
            if kw in name:
                return sector
    return ""


def main() -> int:
    input_path = Path("data/csi300_cons.csv")
    output_path = Path("data/csi300_cons_with_sectors.csv")

    if not input_path.exists():
        print(f"Error: {input_path} not found")
        return 1

    rows: list[dict[str, str]] = []
    with input_path.open("r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if not row.get("sector"):
                row["sector"] = infer_sector(row.get("name", ""))
            rows.append(row)

    with output_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["symbol", "name", "sector"])
        writer.writeheader()
        writer.writerows(rows)

    matched = sum(1 for r in rows if r["sector"])
    print(f"Wrote {len(rows)} stocks to {output_path}")
    print(f"Sector inferred: {matched}/{len(rows)} ({matched/len(rows)*100:.1f}%)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
